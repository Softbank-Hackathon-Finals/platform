"""실제 Postgres가 있을 때만 돈다: TEST_DATABASE_URL (관리자 역할, 스키마 적용 권한 필요)."""

import os
import uuid

import psycopg
import pytest

from bravo_loadgen.db import fetch_rows
from bravo_loadgen.journal import message_author, message_body

DSN = os.environ.get("TEST_DATABASE_URL")
pytestmark = pytest.mark.skipif(not DSN, reason="TEST_DATABASE_URL이 없다")
TABLE = """
CREATE TABLE IF NOT EXISTS messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key uuid NOT NULL UNIQUE,
    author text NOT NULL,
    body text NOT NULL,
    attachment_id uuid,
    created_at timestamptz NOT NULL DEFAULT now()
)
"""


@pytest.fixture
def run_id():
    with psycopg.connect(DSN, autocommit=True) as connection:
        connection.execute(TABLE)
    return f"t18-db-{uuid.uuid4().hex[:12]}"


def insert(run_id, *, key=None, author=None, body=None):
    key = key or str(uuid.uuid4())
    with psycopg.connect(DSN, autocommit=True) as connection:
        connection.execute(
            "INSERT INTO messages (idempotency_key, author, body) VALUES (%s, %s, %s)",
            (key, author or message_author(run_id), body or message_body(run_id, key)),
        )
    return key


def test_fetch_finds_rows_by_key_author_and_body_marker(run_id):
    by_author = insert(run_id)
    by_key = insert(run_id, author="tampered", body="tampered")
    by_body = insert(run_id, author="tampered")
    unrelated = insert("t18-other", author="someone", body="hello")

    rows = fetch_rows(DSN, run_id, [by_key])
    found = {r["idempotency_key"] for r in rows}
    assert {by_author, by_key, by_body} <= found and unrelated not in found
    assert isinstance(rows[0]["idempotency_key"], str)


def test_fetch_opens_a_read_only_transaction(run_id, monkeypatch):
    import bravo_loadgen.db as db

    monkeypatch.setattr(db, "_ROWS_SQL", "INSERT INTO messages (idempotency_key, author, body) "
                        "SELECT gen_random_uuid(), %(author)s, %(marker)s WHERE %(keys)s::uuid[] IS NOT NULL")
    with pytest.raises(psycopg.errors.ReadOnlySqlTransaction):
        fetch_rows(DSN, run_id, [])
