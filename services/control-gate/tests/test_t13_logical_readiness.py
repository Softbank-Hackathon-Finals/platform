"""Actual local PG logical replication/sequence receipt → T19 readiness.

Two databases of one disposable TLS PostgreSQL process, not two team sites.
Context/record authorization remain test authorities. No external workloads.
"""

import secrets
import time
from dataclasses import replace
from datetime import UTC, datetime, timedelta

import psycopg
from bravo_cutover.db_fingerprint import (
    correct_sequence,
    fingerprint,
    next_safe_value,
    sequence_state,
)
from bravo_cutover.remote.db import DbControl
from psycopg import sql
from psycopg.conninfo import make_conninfo
from test_t13_capture import actual_capture, tls_postgres  # noqa: F401

from bravo_gate.readiness import assess_readiness
from bravo_gate.t13 import assemble_snapshot, collect_schema


def test_real_replication_and_sequence_readback_cannot_be_replaced_by_proposal(actual_capture):  # noqa: F811
    ctx, base_policy, regs, connect, _, admin = actual_capture
    policy = replace(
        base_policy, sequence_columns=(("public.messages", "id"),), max_lag_bytes=1024 * 1024
    )
    source_params = admin | {"dbname": regs["source"].database_name}
    target_params = admin | {"dbname": regs["target"].database_name}
    subscription = "testsub_" + secrets.token_hex(5)
    slot = "testslot_" + secrets.token_hex(5)
    role = "repl_" + secrets.token_hex(5)
    with psycopg.connect(**source_params) as source, psycopg.connect(**target_params) as target:
        for conn in (source, target):
            conn.execute(
                "ALTER TABLE public.messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY"
            )
            conn.execute("GRANT SELECT ON ALL SEQUENCES IN SCHEMA public TO reader")
        source.execute(
            sql.SQL("CREATE ROLE {} LOGIN REPLICATION PASSWORD {}").format(
                sql.Identifier(role), sql.Literal(admin["password"])
            )
        )
        source.execute(
            sql.SQL("GRANT SELECT ON public.messages TO {}").format(sql.Identifier(role))
        )
        source.execute("CREATE PUBLICATION readiness_pub FOR TABLE public.messages")
        source.execute(
            "INSERT INTO public.messages(body) SELECT 'test-'||i FROM generate_series(1,5) i"
        )
        # Explicit slot creation avoids same-postmaster CREATE SUBSCRIPTION's
        # wait-for-slot-creation deadlock. The subscription still uses actual TLS.
        source.execute("SELECT pg_create_logical_replication_slot(%s, 'pgoutput')", (slot,))
        replication_dsn = make_conninfo(
            host="127.0.0.1",
            port=5432,
            dbname=regs["source"].database_name,
            user=role,
            password=admin["password"],
            sslmode="verify-full",
            sslrootcert="/certs/server.crt",
        )
        try:
            target.execute(
                sql.SQL(
                    "CREATE SUBSCRIPTION {} CONNECTION {} PUBLICATION readiness_pub WITH (create_slot=false, slot_name={})"
                ).format(
                    sql.Identifier(subscription), sql.Literal(replication_dsn), sql.Literal(slot)
                )
            )
            until = time.monotonic() + 30
            while target.execute("SELECT count(*) FROM public.messages").fetchone()[0] != 5:
                if time.monotonic() > until:
                    raise AssertionError("local_logical_replication_timeout")
                time.sleep(0.2)
            assert fingerprint(source, "public.messages") == fingerprint(target, "public.messages")
            # No live application is running in this fixture. Production must
            # fence every writer and drain transactions before this T13 call.
            a = sequence_state(source, "public.messages_id_seq", "public.messages", "id")
            b = sequence_state(target, "public.messages_id_seq", "public.messages", "id")
            assert b.next_value <= b.max_id
            wanted = next_safe_value(a, b)
            proposal = dict(
                table="public.messages",
                column="id",
                source_next=a.next_value,
                target_next=b.next_value,
                target_max_id=b.max_id,
                proposed_next=wanted,
                readback_next=b.next_value,
                increment=1,
                cycle=False,
            )

            def evaluate(seq, *, known_replication=True):
                source_capture = collect_schema(
                    ctx,
                    policy,
                    regs["source"],
                    side="source",
                    connect=connect,
                    clock=lambda: datetime.now(UTC),
                )
                target_capture = collect_schema(
                    ctx,
                    policy,
                    regs["target"],
                    side="target",
                    connect=connect,
                    clock=lambda: datetime.now(UTC),
                )
                active, lag = source.execute(
                    "SELECT active, pg_wal_lsn_diff(pg_current_wal_lsn(), confirmed_flush_lsn)::bigint FROM pg_replication_slots WHERE slot_name=%s",
                    (slot,),
                ).fetchone()
                # Non-active/unknown replication does not manufacture a zero.
                if known_replication:
                    assert active and lag is not None
                now = datetime.now(UTC)
                timing = dict(
                    observed_at=now.isoformat(),
                    expires_at=(now + timedelta(seconds=20)).isoformat(),
                )
                rep = dict(
                    source_database_ref=regs["source"].database_ref,
                    target_database_ref=regs["target"].database_ref,
                    lag_bytes=lag if active and known_replication else None,
                    **timing,
                )
                binding, snapshot = assemble_snapshot(
                    ctx,
                    policy,
                    source_capture,
                    target_capture,
                    snapshot_ref="actual-local-replication",
                    replication=rep,
                    sequences=[seq | timing],
                )
                return assess_readiness(ctx, binding, snapshot, now=now)

            report = evaluate(proposal)
            assert report["decision"] == "BLOCK"
            assert any(r["reason"] == "SEQUENCE_REHEARSAL_FAILED" for r in report["rows"])
            receipt = correct_sequence(
                DbControl(
                    make_conninfo(**{k: v for k, v in source_params.items() if k != "autocommit"})
                ),
                DbControl(
                    make_conninfo(**{k: v for k, v in target_params.items() if k != "autocommit"})
                ),
                "public.messages_id_seq",
                "public.messages",
                "id",
            )
            repaired = proposal | dict(readback_next=receipt["dst_set"])
            assert receipt["dst_set"] == wanted
            assert evaluate(repaired)["decision"] == "PASS"
            assert evaluate(repaired, known_replication=False)["decision"] == "BLOCK"
        finally:
            target.execute(
                sql.SQL("DROP SUBSCRIPTION IF EXISTS {}").format(sql.Identifier(subscription))
            )
            remaining = source.execute(
                "SELECT slot_name FROM pg_replication_slots WHERE slot_name=%s", (slot,)
            ).fetchone()
            if remaining:
                source.execute("SELECT pg_drop_replication_slot(%s)", (slot,))
