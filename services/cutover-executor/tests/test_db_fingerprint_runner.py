"""T13 비교기의 실제 결과가 실행 단계 판정을 그대로 통과하는지 본다(T12 연결 계약).

원격 조작과 시퀀스는 test_runner_fakes의 가짜이고, 비교만 실제 PostgreSQL DB 두 개에서 돈다.
"""

import json

import psycopg
import pytest

from bravo_cutover.contract import Status
from bravo_cutover.db_fingerprint import HASH_RULE, DbFingerprintComparer
from bravo_cutover.remote.db import DbControl
from tests.test_db_fingerprint import pair, run  # noqa: F401
from tests.test_runner_fakes import CONFIG, FakeCutover, start, world  # noqa: F401


class RealDatabases:
    """실행기가 넘기는 가짜 DB 대신 실제 두 DB를 비교한다. 표 목록은 실행기 설정 그대로다."""

    def __init__(self, dsns):
        self.sides = [DbControl(dsn) for dsn in dsns]

    def compare(self, src, dst, tables):
        return DbFingerprintComparer().compare(*self.sides, tables)


@pytest.fixture
def tables(pair):  # noqa: F811
    for dsn in pair:
        with psycopg.connect(dsn, autocommit=True) as conn:
            conn.execute("CREATE TABLE attachments (id uuid PRIMARY KEY, filename text NOT NULL)")
            conn.execute("""CREATE TABLE messages (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                body text NOT NULL, created_at timestamptz NOT NULL)""")
            conn.execute("INSERT INTO messages VALUES (1, '본문', '2026-11-03T12:00:00Z')")
    return pair


def execute(store, world, dsns):  # noqa: F811
    execution_id = start(store)
    FakeCutover(store, world, comparer=RealDatabases(dsns)).run(execution_id)
    return store.get(execution_id)


def test_real_match_proceeds_and_keeps_the_rule_in_the_receipt(store, world, tables):  # noqa: F811
    execution = execute(store, world, tables)
    assert execution.status == Status.DONE, execution.result
    receipt = execution.result["receipt"]
    assert (receipt["verdict"], receipt["hash_rule"]) == ("MATCH", HASH_RULE)
    assert {t["name"] for t in receipt["tables"]} == set(CONFIG.settings.tables)
    assert all(t["data_verdict"] == t["schema_verdict"] == "MATCH" for t in receipt["tables"])
    assert "dst.set_login:True" in world.calls


@pytest.mark.parametrize("change, verdict, data, schema", [
    ("UPDATE messages SET body='다른 본문' WHERE id=1", "MISMATCH", "MISMATCH", "MATCH"),
    ("ALTER TABLE messages ADD CONSTRAINT short_body CHECK (length(body) < 100)", "MISMATCH", "MATCH", "MISMATCH"),
    ("ALTER TABLE messages ADD COLUMN extra money", "UNKNOWN", "UNKNOWN", "UNKNOWN"),
])
def test_real_failure_does_not_open_target_and_is_recorded(store, world, tables, change, verdict, data, schema):  # noqa: F811
    run(tables[1], change)
    execution = execute(store, world, tables)
    assert execution.status == Status.ABORT_PRE_WRITE, execution.result
    assert execution.result["failed_step"] == "compare"
    assert "dst.set_login:True" not in world.calls and world.login["dst"] is False
    receipt = execution.result["receipt"]
    assert receipt["verdict"] == verdict
    messages = next(t for t in receipt["tables"] if t["name"] == "public.messages")
    assert (messages["data_verdict"], messages["schema_verdict"]) == (data, schema)


def test_connection_error_text_stays_out_of_the_stored_result(store, world, tables):  # noqa: F811
    secret = "FIXTURE-PRIVATE-VALUE"
    execution = execute(store, world, [tables[0], f"host=secret.internal port={secret} user={secret} dbname=chat"])
    assert execution.status == Status.ABORT_PRE_WRITE, execution.result
    assert execution.result["receipt"]["verdict"] == "UNKNOWN"
    assert secret not in json.dumps(execution.result) and "secret.internal" not in json.dumps(execution.result)
