# API -------------------------------------------------------------------------

class Store:
    def __init__(self, unfinished=()):
        self._unfinished = list(unfinished)

    def unfinished(self):
        return self._unfinished


class Observer:
    def __init__(self):
        self.calls = []

    def observe(self, request):
        self.calls.append(request)
        return {"kind": "t13-readiness-observation.v1"}


def client(token, store=None, observer=None):
    app = create_app(store or Store(), object(), object(), api_token="read-fixture", command_token="command-fixture",
                     readiness=observer)
    return TestClient(app, headers={"Authorization": f"Bearer {token}"})


BODY = request().model_dump()


def test_readiness_needs_the_command_credential():
    observer = Observer()
    assert client("read-fixture", observer=observer).post("/v1/readiness", json=BODY).status_code == 403
    response = client("command-fixture", observer=observer).post("/v1/readiness", json=BODY)
    assert response.status_code == 200 and response.json() == {"kind": "t13-readiness-observation.v1"}
    assert len(observer.calls) == 1


def test_readiness_is_refused_while_an_execution_is_unfinished_or_unconfigured():
    observer = Observer()
    busy = client("command-fixture", store=Store(["running"]), observer=observer).post("/v1/readiness", json=BODY)
    assert busy.status_code == 409 and busy.json()["detail"]["code"] == "execution_in_progress"
    assert observer.calls == []
    missing = client("command-fixture").post("/v1/readiness", json=BODY)
    assert missing.status_code == 503 and missing.json()["detail"]["code"] == "executor_not_configured"
    extra = client("command-fixture", observer=observer).post("/v1/readiness", json=BODY | {"setval": 9})
    assert extra.status_code == 422 and observer.calls == []
