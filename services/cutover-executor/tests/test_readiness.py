TABLES = ["public.attachments", "public.messages"]


def site(env, ns, dsn="fake", app_role="chat_app"):
    return Site(environment_id=env, resource_id=f"cnpg-{ns}/chat", connection_ref=f"secret/{ns}",
                kube_context="fake", namespace=ns, subscription=f"sub_{ns}", app_role=app_role,
                pgbouncer_admin_dsn="fake", pgbouncer_app_dsn="fake", db_control_dsn=dsn, db_app_dsn="fake",
                db_host=f"{ns}-db")


def config(src_dsn="src", dst_dsn="dst", app_role="chat_app"):
    return Config(settings=Settings(), origin="env-aws",
                  sites={"env-aws": site("env-aws", "aws", src_dsn, app_role),
                         "env-onprem": site("env-onprem", "onprem", dst_dsn, app_role)})


def request(**override):
    return ReadinessRequest(**({"source_environment_id": "env-aws", "target_environment_id": "env-onprem",
                                "tables": TABLES, "sequence_columns": [["public.messages", "id"]]} | override))


# 실제 PostgreSQL --------------------------------------------------------------

def seed(dsn, ids, *, copy_only):
    with psycopg.connect(dsn, autocommit=True) as conn:
        conn.execute("CREATE TABLE messages (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, body text NOT NULL)")
        conn.execute("CREATE TABLE attachments (id uuid PRIMARY KEY, message_id bigint NOT NULL)")
        for i in ids:
            if copy_only:  # 논리 복제처럼 값만 옮긴다: 목적지 시퀀스는 움직이지 않는다
                conn.execute("INSERT INTO messages (id, body) VALUES (%s, %s)", (i, f"m{i}"))
            else:
                conn.execute("INSERT INTO messages (body) VALUES (%s)", (f"m{i}",))


@pytest.fixture
def databases(postgres_dsn):
    names = ["ready_" + uuid4().hex for _ in range(2)]
    role = "app_" + uuid4().hex[:12]
    with psycopg.connect(postgres_dsn, autocommit=True) as admin:
        admin.execute(sql.SQL("CREATE ROLE {} NOLOGIN").format(sql.Identifier(role)))
        try:
            for name in names:
                admin.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))
            dsns = [make_conninfo(**(conninfo_to_dict(postgres_dsn) | {"dbname": n})) for n in names]
            seed(dsns[0], range(1, 6), copy_only=False)
            seed(dsns[1], range(1, 6), copy_only=True)
            yield dsns, role
        finally:
            for name in names:
                admin.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(name)))
            admin.execute(sql.SQL("DROP ROLE IF EXISTS {}").format(sql.Identifier(role)))


def target_next(dsn):
    return DbControl(dsn).sequence_next("public.messages_id_seq")


def test_closed_target_sequence_is_raised_once_and_read_back(databases):
    (src, dst), role = databases
    assert target_next(dst) == 1
    result = Readiness(config(src, dst, role)).observe(request())
    assert result["kind"] == "t13-readiness-observation.v1" and result["schema_rule"] == HASH_RULE
    for side, env in (("source", "env-aws"), ("target", "env-onprem")):
        assert result[side]["environment_id"] == env and result[side]["errors"] == {}
        assert [t["name"] for t in result[side]["tables"]] == TABLES
    assert result["source"]["tables"] == result["target"]["tables"]
    assert all(t["schema_hash"] and t["primary_key"] for t in result["source"]["tables"])
    [row] = result["sequences"]
    assert (row["source_next"], row["target_next"], row["target_max_id"]) == (6, 1, 5)
    assert row["proposed_next"] == row["readback_next"] == 6 and target_next(dst) == 6
    assert result["sequence_errors"] == {}
    # 구독이 없으면 지연은 알 수 없음으로 남는다(0으로 채우지 않는다)
    assert result["replication"]["lag_bytes"] is None and result["replication_error"] == "replication_unconfirmed"
    assert result["replication"]["source_database_ref"] == "cnpg-aws/chat"
    # 다시 관찰해도 더 올리지 않는다
    [again] = Readiness(config(src, dst, role)).observe(request())["sequences"]
    assert (again["target_next"], again["proposed_next"], again["readback_next"]) == (6, 6, 6)
    assert target_next(dst) == 6


def test_open_target_is_never_written(databases, postgres_dsn):
    (src, dst), role = databases
    with psycopg.connect(postgres_dsn, autocommit=True) as admin:
        admin.execute(sql.SQL("ALTER ROLE {} LOGIN").format(sql.Identifier(role)))
    result = Readiness(config(src, dst, role)).observe(request())
    assert result["sequences"] == [] and result["sequence_errors"] == {"public.messages:id": "target_open"}
    assert target_next(dst) == 1


def test_schema_difference_is_reported_not_judged(databases):
    (src, dst), role = databases
    with psycopg.connect(dst, autocommit=True) as conn:
        conn.execute("ALTER TABLE messages ADD COLUMN edited boolean")
    result = Readiness(config(src, dst, role)).observe(request(sequence_columns=[]))
    by_side = {side: {t["name"]: t["schema_hash"] for t in result[side]["tables"]} for side in ("source", "target")}
    assert by_side["source"]["public.messages"] != by_side["target"]["public.messages"]
    assert by_side["source"]["public.attachments"] == by_side["target"]["public.attachments"]
    assert result["sequences"] == [] and target_next(dst) == 1


# 가짜 DB ----------------------------------------------------------------------

class FakeDb:
    def __init__(self, world, side):
        self.w, self.side = world, side

    def schema_fingerprint(self, table):
        reads = self.w["reads"].setdefault((self.side, table), [])
        reads.append(1)
        if fail := self.w["schema_fail"].get((self.side, table, len(reads))):
            raise fail
        return {"schema_hash": f"h-{table}-{self.w['version'].get((self.side, table, len(reads)), 1)}",
                "primary_key": ["id"]}

    def subscription(self, name):
        return self.w["sub"]

    def received_lsn(self, name):
        return self.w["received"]

    def current_wal_lsn(self):
        return self.w["wal"]

    def can_login(self, role):
        if self.w["login"] is None:
            raise Unconfirmed("control connection: host=secret-host password=secret")
        return self.w["login"]

    def sessions(self, role):
        return self.w["sessions"]

    def sequence_state(self, sequence, table, column):
        return self.w["seq"][self.side]

    def raise_sequence(self, sequence, next_value):
        self.w["raised"].append(next_value)
        if self.w["readback_lost"]:
            return next_value
        s = self.w["seq"][self.side]
        self.w["seq"][self.side] = SequenceState(next_value, False, s.max_id, s.maximum)
        return next_value


def world(**override):
    return {"reads": {}, "schema_fail": {}, "version": {}, "received": 900, "wal": 1000, "login": False,
            "sessions": 0, "raised": [], "sub": Subscription(enabled=True, workers=1), "readback_lost": False,
            "seq": {"src": SequenceState(20, True, 20, 2**63 - 1), "dst": SequenceState(3, True, 20, 2**63 - 1)}
            } | override


def fake(w, clock=None):
    sides = {"src": "src", "dst": "dst"}
    return Readiness(config(), db=lambda dsn, control_functions: FakeDb(w, sides[dsn]),
                     **({"clock": clock} if clock else {}))


def test_lag_and_raise_follow_the_executor_rules():
    w = world()
    result = fake(w).observe(request())
    assert result["replication"]["lag_bytes"] == 100 and result["replication_error"] is None
    assert w["raised"] == [21] and result["sequences"][0]["readback_next"] == 21


@pytest.mark.parametrize("sub", [Subscription(enabled=False, workers=0), Subscription(enabled=True, workers=0)])
def test_a_stopped_forward_subscription_leaves_lag_unknown(sub):
    result = fake(world(sub=sub)).observe(request(sequence_columns=[]))
    assert result["replication"]["lag_bytes"] is None and result["replication_error"] == "replication_not_running"


def test_the_proposal_covers_ids_written_past_either_sequence():
    # 출발지에 값을 지정해 넣은 행이 시퀀스보다 앞서 있고, 목적지에는 아직 오지 않았다
    w = world(seq={"src": SequenceState(20, True, 40, 2**63 - 1), "dst": SequenceState(3, True, 20, 2**63 - 1)})
    [row] = fake(w).observe(request())["sequences"]
    assert row["proposed_next"] == row["readback_next"] == 41 and w["raised"] == [41]


def test_a_raise_that_does_not_read_back_drops_the_row():
    w = world(readback_lost=True)
    result = fake(w).observe(request())
    assert w["raised"] == [21] and result["sequences"] == []
    assert result["sequence_errors"] == {"public.messages:id": "sequence_readback_mismatch"}


def test_schema_changed_between_reads_is_cleared():
    w = world(version={("dst", "public.messages", 2): 2})
    result = fake(w).observe(request(sequence_columns=[]))
    target = {t["name"]: t for t in result["target"]["tables"]}
    assert target["public.messages"]["schema_hash"] is None and target["public.messages"]["primary_key"] is None
    assert result["target"]["errors"] == {"public.messages": "schema_changed"}
    assert target["public.attachments"]["schema_hash"] == "h-public.attachments-1"


def test_failures_leave_only_fixed_codes():
    w = world(login=None, schema_fail={("src", "public.messages", 1): FingerprintUnconfirmed("table_missing")})
    result = fake(w).observe(request())
    assert result["source"]["errors"] == {"public.messages": "table_missing"}
    assert result["sequence_errors"] == {"public.messages:id": "target_state_unconfirmed"} and w["raised"] == []
    assert "secret" not in repr(result)


def test_sessions_opened_before_nologin_keep_the_target_open():
    w = world(sessions=1)
    assert fake(w).observe(request())["sequence_errors"] == {"public.messages:id": "target_open"}
    assert w["raised"] == []


