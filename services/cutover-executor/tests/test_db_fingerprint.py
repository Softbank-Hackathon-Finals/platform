@pytest.mark.parametrize("swap", [False, True], ids=["forward", "reverse"])
def test_different_major_versions_are_unknown_even_with_equal_fingerprints(across_majors, swap):
    result = compare(across_majors[::-1] if swap else across_majors)
    table = result["tables"][0]
    # 시험 전제: 실제로 메이저가 다르고, 행 지문은 같다. 같아도 호환을 검증한 적이 없으므로 통과시키지 않는다.
    source, target = table["source"], table["target"]
    assert {source["server_major"], target["server_major"]} == {16, 18}
    assert all(source[key] == target[key] for key in ("rows", "pk_hash", "content_hash"))
    assert (result["verdict"], result["data_verdict"], result["schema_verdict"]) == ("UNKNOWN", "UNKNOWN", "UNKNOWN")
    assert table["match"] is False and table["rows_src"] == table["rows_dst"] == 3
    assert table["error"] == "major_version_mismatch"


