def run(dsn, *queries):
    with psycopg.connect(dsn, autocommit=True) as conn:
        result = None
        for query in queries:
            result = conn.execute(query)
        return result.fetchall() if result is not None and result.description else None


def compare(pair, tables=(TABLE,)):
    return DbFingerprintComparer().compare(DbControl(pair[0]), DbControl(pair[1]), list(tables))


def hashes(dsn, table=TABLE):
    with psycopg.connect(dsn, autocommit=True) as conn:
        return fingerprint(conn, table)


