def test_statement_timeout_of_three_seconds_is_unconfirmed(pair):
    # 지문 쿼리를 잠금으로 붙잡아 실제 3초 제한이 서버에서 끊는지 본다. 연결에 제한을 걸지 않아 함수의 제한만 작동한다.
    with psycopg.connect(pair[1]) as holder, psycopg.connect(pair[1], autocommit=True) as conn:
        holder.execute("LOCK TABLE sample IN ACCESS EXCLUSIVE MODE")
        started = time.monotonic()
        with pytest.raises(Unconfirmed, match="statement_timeout"):
            fingerprint(conn, TABLE)
        assert 2.5 < time.monotonic() - started < 6
        holder.rollback()


