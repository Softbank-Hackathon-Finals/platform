class Side:
    """지문을 정해 둔 비교 상대. 실제 DB로는 만들 수 없는 조합의 판정만 본다."""

    def __init__(self, **values):
        self.values = {"rows": 1, "pk_hash": "p", "content_hash": "c", "schema_hash": "s",
                       "schema_definition_hash": "d", "server_major": 18} | values

    def db_fingerprint(self, table):
        return self.values


@pytest.mark.parametrize("target, data, schema, verdict", [
    (Side(), "MATCH", "MATCH", "MATCH"),
    (Side(rows=2), "MISMATCH", "MATCH", "MISMATCH"),
    (Side(pk_hash="other"), "MISMATCH", "MATCH", "MISMATCH"),
    (Side(content_hash="other"), "MISMATCH", "MATCH", "MISMATCH"),
    (Side(schema_hash="other"), "MATCH", "UNKNOWN", "UNKNOWN"),
    (Side(schema_hash="other", schema_definition_hash="other"), "MATCH", "MISMATCH", "MISMATCH"),
    (Side(content_hash="other", schema_hash="other"), "MISMATCH", "UNKNOWN", "MISMATCH"),
    (Side(server_major=16), "UNKNOWN", "UNKNOWN", "UNKNOWN"),
    (Side(server_major=16, content_hash="other", schema_hash="other", schema_definition_hash="other"),
     "UNKNOWN", "UNKNOWN", "UNKNOWN"),  # 표현이 달라 생긴 차이일 수 있어 MISMATCH라고 단정하지 않는다
])
def test_verdict_table(target, data, schema, verdict):
    result = DbFingerprintComparer().compare(Side(), target, [TABLE])
    assert (result["data_verdict"], result["schema_verdict"], result["verdict"]) == (data, schema, verdict)
    assert result["tables"][0]["match"] is (verdict == "MATCH")


