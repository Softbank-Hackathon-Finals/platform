def test_row_security_cannot_silently_hide_rows(pair, postgres_dsn):
    role = "t13_" + uuid4().hex
    with psycopg.connect(postgres_dsn, autocommit=True) as admin:
        admin.execute(sql.SQL("CREATE ROLE {}").format(sql.Identifier(role)))
    try:
        for dsn in pair:
            run(dsn, sql.SQL("GRANT SELECT ON sample TO {}").format(sql.Identifier(role)),
                "ALTER TABLE sample ENABLE ROW LEVEL SECURITY", "CREATE POLICY hide_all ON sample USING (false)")
        with psycopg.connect(pair[0], autocommit=True) as conn:
            conn.execute(sql.SQL("SET ROLE {}").format(sql.Identifier(role)))
            # 시험 전제: 제한 없이 읽으면 오류 없이 0행이다. 양쪽이 같으면 MATCH로 보일 수 있다.
            assert conn.execute("SELECT count(*) FROM sample").fetchone() == (0,)
            with pytest.raises(Unconfirmed, match="42501"):
                fingerprint(conn, TABLE)
    finally:
        for dsn in pair:
            run(dsn, "DROP POLICY hide_all ON sample", sql.SQL("REVOKE ALL ON sample FROM {}").format(sql.Identifier(role)))
        with psycopg.connect(postgres_dsn, autocommit=True) as admin:
            admin.execute(sql.SQL("DROP ROLE {}").format(sql.Identifier(role)))


def test_select_only_role_is_enough(pair, postgres_dsn):
    # 실제 cutover_control은 표와 시퀀스 SELECT만 있다(testing/sql/30-cutover.sql). 슈퍼유저로만 돌던 코드가 되면 안 된다.
    role = "t13_" + uuid4().hex
    identifier = sql.Identifier(role)
    with psycopg.connect(postgres_dsn, autocommit=True) as admin:
        admin.execute(sql.SQL("CREATE ROLE {} NOSUPERUSER").format(identifier))
    try:
        run(pair[0], sql.SQL("GRANT SELECT ON sample, events TO {}").format(identifier),
            sql.SQL("GRANT SELECT ON SEQUENCE public.events_id_seq TO {}").format(identifier))
        expected = hashes(pair[0])
        with psycopg.connect(pair[0], autocommit=True) as conn:
            conn.execute(sql.SQL("SET ROLE {}").format(identifier))
            assert fingerprint(conn, TABLE) == expected
            assert sequence_state(conn, *SEQUENCE).next_value == 1
    finally:
        run(pair[0], sql.SQL("REVOKE ALL ON sample, events FROM {}").format(identifier),
            sql.SQL("REVOKE ALL ON SEQUENCE public.events_id_seq FROM {}").format(identifier))
        with psycopg.connect(postgres_dsn, autocommit=True) as admin:
            admin.execute(sql.SQL("DROP ROLE {}").format(identifier))


