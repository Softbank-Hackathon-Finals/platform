from pathlib import Path

from psycopg.conninfo import make_conninfo

from bravo_cutover import db_fingerprint
from bravo_cutover.db_fingerprint import DbFingerprintComparer
from bravo_cutover.remote.db import DbControl

IMAGE = "public.ecr.aws/docker/library/postgres:18.4"
# 데비안 버전이 달라 glibc(정렬 제공자) 버전이 다른 이미지
OTHER_PROVIDER_IMAGE = "public.ecr.aws/docker/library/postgres:18.4-bookworm"
TABLES = ["public.attachments", "public.messages"]
PASSWORD = uuid.uuid4().hex

# infra/envs/source-workloads/schema.sql의 두 표
SCHEMA = """CREATE TABLE attachments (id uuid PRIMARY KEY, object_key text NOT NULL, filename text NOT NULL,
  content_type text NOT NULL, size integer NOT NULL CHECK (size >= 0), created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE messages (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, idempotency_key uuid NOT NULL UNIQUE,
  author text NOT NULL, body text NOT NULL, attachment_id uuid REFERENCES attachments (id),
  created_at timestamptz NOT NULL DEFAULT now());
"""
SEED = """INSERT INTO attachments(id,object_key,filename,content_type,size,created_at)
 SELECT md5('a'||g)::uuid,'obj/'||g,'파일 '||g||'.pdf','application/pdf',g,
   timestamptz '2026-11-01 00:00:00+00'+g*interval '1 microsecond' FROM generate_series(1,2000) g;
INSERT INTO messages(id,idempotency_key,author,body,attachment_id,created_at)
 SELECT g,md5('k'||g)::uuid,CASE WHEN g%2=0 THEN '고객' ELSE '상담' END,
   '상담 내용 '||g||' '||(SELECT string_agg(md5(g::text||i::text),'') FROM generate_series(1,60) i),
   CASE WHEN g%50=0 THEN md5('a'||(g%2000+1))::uuid END,
   timestamptz '2026-11-01 00:00:00+00'+g*interval '1 millisecond' FROM generate_series(1,100000) g;
SELECT setval(pg_get_serial_sequence('messages','id'),100000);
VACUUM ANALYZE;
"""


def sh(*args, stdin=None) -> str:
    result = subprocess.run(args, input=stdin, text=True, capture_output=True)
    if result.returncode:
        raise SystemExit(f"{args[:3]}: {result.stderr[:300]}")
    return result.stdout.strip()


class Server:
    def __init__(self, image: str):
        self.name = f"t13-measure-{uuid.uuid4().hex[:8]}"
        sh("docker", "run", "-d", "--rm", "--name", self.name, "-e", f"POSTGRES_PASSWORD={PASSWORD}",
           "-p", "127.0.0.1::5432", image)
        self.port = int(sh("docker", "port", self.name, "5432/tcp").rsplit(":", 1)[1])
        self.image_id = sh("docker", "image", "inspect", image, "--format", "{{.Id}}")
        for _ in range(90):
            if subprocess.run(["docker", "exec", self.name, "pg_isready", "-U", "postgres", "-h", "127.0.0.1"],
                              capture_output=True).returncode == 0:
                return
            time.sleep(1)
        self.stop()
        raise SystemExit("postgres did not start")

    def psql(self, db: str, text: str) -> str:
        return sh("docker", "exec", "-i", self.name, "psql", "-U", "postgres", "-d", db, "-X", "-q", "-A", "-t",
                  "-v", "ON_ERROR_STOP=1", stdin=text)

    def create(self, db: str, locale: str, timezone: str, seed: bool = True) -> None:
        self.psql("postgres", f"CREATE DATABASE {db} TEMPLATE template0 ENCODING 'UTF8' LOCALE '{locale}';")
        self.psql(db, f"ALTER DATABASE {db} SET TimeZone='{timezone}';")
        self.psql(db, SCHEMA)
        if seed:
            self.psql(db, SEED)

    def dsn(self, db: str, port: int | None = None) -> str:
        return make_conninfo(host="127.0.0.1", port=port or self.port, dbname=db, user="postgres", password=PASSWORD)

    def stop(self) -> None:
        subprocess.run(["docker", "rm", "-f", self.name], capture_output=True)


class CountingProxy:
    """목적지 연결만 거치게 해 오간 바이트와 클라이언트 전송 횟수를 센다. 대역폭 제한은 걸지 않는다."""

    def __init__(self, target_port: int):
        self.target_port, self.down, self.up, self.client_sends = target_port, 0, 0, 0
        self.listener = socket.create_server(("127.0.0.1", 0))
        self.port = self.listener.getsockname()[1]
        threading.Thread(target=self._accept, daemon=True).start()

    def _accept(self) -> None:
        while True:
            client, _ = self.listener.accept()
            server = socket.create_connection(("127.0.0.1", self.target_port))
            threading.Thread(target=self._pump, args=(client, server, True), daemon=True).start()
            threading.Thread(target=self._pump, args=(server, client, False), daemon=True).start()

    def _pump(self, source, sink, upstream: bool) -> None:
        try:
            while data := source.recv(1 << 16):
                sink.sendall(data)
                if upstream:
                    self.up += len(data)
                    self.client_sends += 1
                else:
                    self.down += len(data)
        except OSError:
            pass
        finally:
            for s in (source, sink):
                s.close()


def timed(call, reps: int) -> dict:
    samples = []
    for _ in range(reps):
        started = time.perf_counter()
        result = call()
        samples.append(time.perf_counter() - started)
    return {"median_s": round(statistics.median(samples), 3), "max_s": round(max(samples), 3),
            "samples_s": [round(s, 3) for s in samples], "last": result}


def db_method(src_dsn: str, dst_dsn: str) -> dict:
    return DbFingerprintComparer().compare(DbControl(src_dsn), DbControl(dst_dsn), TABLES)


def baseline_method(module):
    def run(src_dsn: str, dst_dsn: str) -> dict:
        out = {}
        for side, dsn in (("source", src_dsn), ("target", dst_dsn)):
            for table in TABLES:
                with DbControl(dsn)._connect() as conn:
                    out[side, table] = module.fingerprint(conn, table)
        same = all(out["source", t] == out["target", t] for t in TABLES)
        return {"verdict": "MATCH" if same else "MISMATCH"}
    return run


def summarize_verdict(result: dict) -> dict:
    return {key: result.get(key) for key in ("verdict", "data_verdict", "schema_verdict") if key in result}


def one_table_times(dsn: str) -> dict:
    times = {}
    for table in TABLES:
        samples = []
        for _ in range(5):
            started = time.perf_counter()
            DbControl(dsn).db_fingerprint(table)
            samples.append(time.perf_counter() - started)
        times[table] = round(statistics.median(samples), 3)
    return times


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--baseline", type=Path)
    parser.add_argument("--reps", type=int, default=5)
    args = parser.parse_args()

    methods = {"db_sql": db_method}
    sources = {"db_fingerprint.py": sha256(Path(db_fingerprint.__file__)), "measure_fingerprint.py": sha256(Path(__file__))}
    if args.baseline:
        spec = importlib.util.spec_from_file_location("baseline_integrity", args.baseline)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        methods["python_134"] = baseline_method(module)
        sources["baseline_integrity.py"] = sha256(args.baseline)

    servers = []
    try:
        for image in (IMAGE, IMAGE, OTHER_PROVIDER_IMAGE):
            servers.append(Server(image))
        source, target, other = servers
        source.create("chat", "C", "UTC")
        target.create("chat", "C", "Asia/Tokyo")
        target.create("chat_en", "en_US.utf8", "UTC")
        src, dst = source.dsn("chat"), target.dsn("chat")
        results = {
            "environment": {
                "statement": "로컬 컨테이너 측정. 실제 Tailscale · TLS 경로, RKE2 위 CNPG, 부하 상태가 아니다. 컷오버를 실행하지 않았다.",
                "network_limit": "없음", "tls": False, "load": "없음", "same_machine": True,
                "image": IMAGE, "image_id": source.image_id,
                "data": {
                    "messages": int(source.psql("chat", "SELECT count(*) FROM messages")),
                    "attachments": int(source.psql("chat", "SELECT count(*) FROM attachments")),
                    "total_mb": round(int(source.psql(
                        "chat", "SELECT pg_total_relation_size('messages')+pg_total_relation_size('attachments')")) / 1048576),
                },
            },
            "source_sha256": sources,
            "hash_rule": db_fingerprint.HASH_RULE,
            "statement_timeout_ms": db_fingerprint.STATEMENT_TIMEOUT_MS,
        }
        # 캐시를 데운 뒤 잰다. 첫 실행 값은 따로 남긴다.
        results["first_run_s"] = {name: timed(lambda m=method: m(src, dst), 1)["median_s"] for name, method in methods.items()}
        results["compare_two_sides"] = {}
        for name, method in methods.items():
            measured = timed(lambda m=method: m(src, dst), args.reps)
            results["compare_two_sides"][name] = {**summarize_verdict(measured.pop("last")), **measured}
        results["one_table_one_side_s"] = {"db_sql": one_table_times(src)}
        results["traffic_from_target"] = {}
        for name, method in methods.items():
            proxy = CountingProxy(target.port)
            method(src, target.dsn("chat", proxy.port))
            time.sleep(0.2)
            results["traffic_from_target"][name] = {
                "received_bytes": proxy.down, "sent_bytes": proxy.up, "client_sends": proxy.client_sends}
        # 같은 데이터, 다른 DB 기본 정렬: 데이터는 같고 스키마만 다르다
        results["collation_differs"] = summarize_verdict(db_method(src, target.dsn("chat_en")))

        # 실제로 제공자 버전이 다른 두 서버: 정의는 같으니 불명이어야 한다
        target.create("small", "en_US.utf8", "UTC", seed=False)
        other.create("small", "en_US.utf8", "UTC", seed=False)
        versions = {side: server.psql("small", "SELECT datcollversion FROM pg_database WHERE datname='small'")
                    for side, server in (("source", target), ("target", other))}
        results["provider_version_differs"] = {
            "image": OTHER_PROVIDER_IMAGE, "versions": versions,
            **summarize_verdict(db_method(target.dsn("small"), other.dsn("small")))}
        args.out.write_text(json.dumps(results, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(json.dumps({k: results[k] for k in ("environment", "first_run_s", "compare_two_sides", "one_table_one_side_s",
                                                  "traffic_from_target", "collation_differs", "provider_version_differs")},
                         ensure_ascii=False, indent=1))
    finally:
        for server in servers:
            server.stop()


if __name__ == "__main__":
    main()
