"""Render one environment's desired state as a Helm chart for that cluster's own Argo CD (pull GitOps).

The chart is generated, deterministic and committed under infra/iac/charts/<environment>. The
tailnet suffix is the chart's only value (`tailnet`, e.g. `<name>.ts.net`): it stays out of the
public repository and is set on the cluster's Argo Application at install. Resources that need
credentials (``secret_inputs``) are not in the chart; their own applier injects them.
"""

import json

from .catalog import check_state, module
from .plan import digest

API = {"ProxyGroup": "tailscale.com/v1alpha1", "Service": "v1", "NetworkPolicy": "networking.k8s.io/v1"}
# Namespaces the chart uses are declared so a fresh cluster gets them; Argo never deletes one (it may
# already hold other workloads) and creates them before anything else.
NAMESPACE_ANNOTATIONS = {"argocd.argoproj.io/sync-options": "Prune=false,Delete=false",
                         "argocd.argoproj.io/sync-wave": "-1"}
SYSTEM_NAMESPACES = {"default", "kube-system", "kube-public", "kube-node-lease"}
TAILNET_PATTERN = r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.ts\.net$"


def manifests(state) -> tuple[list[dict], list[str]]:
    """(Kubernetes objects, modules or resources left to another applier)."""
    state = check_state(state)
    objects, unmanaged = [], []
    for entry in state["modules"]:
        for resource in module(entry["id"], entry["version"]).render(entry["params"]):
            key = f'{resource["kind"]}/{resource["namespace"]}/{resource["name"]}'
            if resource.get("secret_inputs") or resource["kind"] not in API:
                unmanaged.append(f'{entry["id"]}:{key}')
                continue
            labels = {"app.kubernetes.io/managed-by": "bravo-iac", "bravo.dev/iac-module": entry["id"]}
            metadata = {"name": resource["name"], "labels": labels}
            if resource["namespace"] != "-":
                metadata["namespace"] = resource["namespace"]
            spec = dict(resource["shape"])
            if resource["kind"] == "Service":
                metadata["annotations"] = spec.pop("annotations")
            objects.append({"apiVersion": API[resource["kind"]], "kind": resource["kind"],
                            "metadata": metadata, "spec": spec})
    namespaces = sorted({o["metadata"]["namespace"] for o in objects if "namespace" in o["metadata"]} - SYSTEM_NAMESPACES)
    declared = [{"apiVersion": "v1", "kind": "Namespace",
                 "metadata": {"name": name, "labels": {"app.kubernetes.io/managed-by": "bravo-iac"},
                              "annotations": dict(NAMESPACE_ANNOTATIONS)}} for name in namespaces]
    return declared + objects, sorted(unmanaged)


def files(state) -> dict[str, str]:
    """path (relative to the chart directory) -> exact content."""
    state = check_state(state)
    objects, unmanaged = manifests(state)
    environment = state["environment"]
    chart = {
        "apiVersion": "v2", "name": f"bravo-iac-{environment}", "type": "application", "version": "0.1.0",
        "description": f"Generated by bravo-iac from infra/iac/environments/{environment}.json; do not edit.",
        "annotations": {"bravo.dev/state-digest": digest(state),
                        "bravo.dev/unmanaged": json.dumps(unmanaged)},
    }
    documents = []
    for obj in objects:
        text = json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False)
        documents.append(text.replace("{tailnet}", "{{ .Values.tailnet }}"))
    template = ('{{- $_ := required "tailnet (the <name>.ts.net suffix) is required" .Values.tailnet }}\n'
                + "".join(f"---\n{d}\n" for d in documents))
    schema = {"$schema": "https://json-schema.org/draft-07/schema#", "type": "object",
              "additionalProperties": False, "required": ["tailnet"],
              "properties": {"tailnet": {"type": "string", "pattern": TAILNET_PATTERN}}}
    return {
        "Chart.yaml": json.dumps(chart, indent=2, sort_keys=True) + "\n",
        "values.yaml": '# The tailnet suffix is set on the cluster\'s Argo Application, never committed.\ntailnet: ""\n',
        "values.schema.json": json.dumps(schema, indent=2, sort_keys=True) + "\n",
        "templates/resources.yaml": template,
    }
