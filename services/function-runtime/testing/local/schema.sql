-- demo-chat messages의 필요한 열만 둔 로컬 스키마와 검사 결과 테이블. 모든 테이블에 PK(설계 8.10).
CREATE ROLE chat_app LOGIN PASSWORD 'local-only';
CREATE TABLE messages (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key uuid   NOT NULL UNIQUE,
    author          text   NOT NULL,
    body            text   NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);
-- PK는 messages 행 번호(message_id). 메시지 하나에 결과 하나라 중복이 생기지 않고, 새 시퀀스가 없어 컷오버 시퀀스 보정 대상이 늘지 않는다.
-- 일치한 값과 본문은 저장하지 않는다. 종류와 개수만 둔다(T22 담당 조건).
CREATE TABLE message_checks (
    message_id      bigint  PRIMARY KEY REFERENCES messages (id),
    has_pii         boolean NOT NULL,
    kinds           text[]  NOT NULL,
    counts          jsonb   NOT NULL,
    sqs_message_id  text    NOT NULL,
    checked_at      timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT ON messages, message_checks TO chat_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO chat_app;
