#!/usr/bin/env python3
"""Render one customer cluster's Tailscale operator into Git (T48, ADR-0035).

    python3 infra/iac/operators/render.py source-dev     # writes infra/iac/operators/source-dev/operator.yaml

The bytes are `helm template` of the pinned chart (sha256 checked) with `target-workloads/network.py values`,
without its CRDs: like the namespace, they belong to whoever builds the cluster (infra/iac/argocd README).
The customer Argo CD (`infra/iac/argocd`, `operator.enabled`) applies this file at the reviewed commit, so a
mode or image change is a reviewed commit and a promotion, never a hand edit on the cluster.
"""
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
NETWORK = ROOT / "infra/envs/target-workloads/network.py"
SIDES = {"source-dev": ["--side", "source"]}  # the clusters whose operator Argo applies


def chart_sha256() -> str:
    for line in NETWORK.read_text().splitlines():
        if line.startswith("CHART_SHA256 = "):
            return line.split('"')[1]
    raise SystemExit("CHART_SHA256 not found")


def main(env: str) -> int:
    if env not in SIDES:
        raise SystemExit(f"unknown environment {env!r}: one of {sorted(SIDES)}")
    values = subprocess.run([sys.executable, str(NETWORK), "values", *SIDES[env]], check=True,
                            capture_output=True, text=True).stdout
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(["helm", "pull", "tailscale-operator", "--repo", "https://pkgs.tailscale.com/helmcharts",
                        "--version", "1.104.4", "--destination", tmp], check=True, capture_output=True)
        [chart] = Path(tmp).glob("tailscale-operator-1.104.4*.tgz")
        if hashlib.sha256(chart.read_bytes()).hexdigest() != chart_sha256():
            raise SystemExit("chart sha256 differs from network.py CHART_SHA256")
        (Path(tmp) / "values.json").write_text(values)
        rendered = subprocess.run(["helm", "template", "tailscale-operator", str(chart), "--namespace",
                                   "tailscale-system", "-f", str(Path(tmp) / "values.json"),
                                   "--set", "installCRDs=false"],
                                  check=True, capture_output=True, text=True).stdout
    header = (f"# Generated by infra/iac/operators/render.py {env}: tailscale-operator 1.104.4 "
              f"(sha256 {chart_sha256()}) with network.py values {' '.join(SIDES[env])}, no CRDs. Do not edit.\n")
    out = ROOT / "infra/iac/operators" / env / "operator.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + rendered)
    written = [str(out.relative_to(ROOT))]
    access = access_objects(env)
    if access:
        path = out.with_name("access.yaml")
        path.write_text(f"# Generated by infra/iac/operators/render.py {env} from its workload-api-access module. Do not edit.\n"
                        + "".join("---\n" + json.dumps(o, indent=2) + "\n" for o in access))
        written.append(str(path.relative_to(ROOT)))
    print(json.dumps({"written": written}))
    return 0


def access_objects(env: str) -> list[dict]:
    """The kube-apiserver ProxyGroup (auth) and one RoleBinding per binding, from the environment's
    workload-api-access module; the policy part comes from the same parameters (bravo-iac tailnet-policy)."""
    state = json.loads((ROOT / "infra/iac/environments" / f"{env}.json").read_text())
    out = []
    for entry in state["modules"]:
        if entry["id"] != "workload-api-access":
            continue
        p = entry["params"]
        out.append({"apiVersion": "tailscale.com/v1alpha1", "kind": "ProxyGroup",
                    "metadata": {"name": p["proxy_hostname"]},
                    "spec": {"type": "kube-apiserver", "replicas": 1, "tags": [p["proxy_tag"]],
                             "kubeAPIServer": {"mode": "auth", "hostname": p["proxy_hostname"]}}})
        for b in p["bindings"]:
            out.append({"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "RoleBinding",
                        "metadata": {"name": b["group"].replace(":", "-"), "namespace": b["namespace"]},
                        "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "Role", "name": b["role"]},
                        "subjects": [{"apiGroup": "rbac.authorization.k8s.io", "kind": "Group", "name": b["group"]}]})
    return out


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1] if len(sys.argv) > 1 else ""))
