-- New development database only. Run as bootstrap administrator, never chat_app.
CREATE TABLE attachments (
    id uuid PRIMARY KEY,
    object_key text NOT NULL,
    filename text NOT NULL,
    content_type text NOT NULL,
    size integer NOT NULL CHECK (size >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key uuid NOT NULL UNIQUE,
    author text NOT NULL,
    body text NOT NULL,
    attachment_id uuid REFERENCES attachments (id),
    created_at timestamptz NOT NULL DEFAULT now()
);
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE chat TO chat_app, chat_replicator;
GRANT USAGE ON SCHEMA public TO chat_app, chat_replicator;
GRANT SELECT, INSERT ON attachments, messages TO chat_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO chat_app;
GRANT SELECT ON attachments, messages TO chat_replicator;
CREATE PUBLICATION source_chat FOR TABLE attachments, messages;
